/**
 * An Astro integration that writes the site's redirects to dist/_redirects after the build, in the
 * format both Cloudflare (wrangler.jsonc) and Netlify read. They're real HTTP 301 redirects at the
 * edge, so they cost nothing and don't need a page at the old URL.
 *
 * - The old Gatsby site served articles at /<slug>/; they're now at /article/<slug>/.
 * - /article itself, which has no page of its own, goes to the homepage.
 */
import { writeFileSync } from "node:fs";
import { articleDates } from "./article-dates.mjs";

export function redirectsFile() {
  let base = "/";

  return {
    name: "redirects-file",
    hooks: {
      "astro:config:done": ({ config }) => {
        base = config.base.endsWith("/") ? config.base : `${config.base}/`;
      },
      "astro:build:done": ({ dir, logger }) => {
        const rules = [
          ["article", ""],
          ["article/", ""],
          ...[...articleDates().keys()].flatMap((slug) => [
            [slug, `article/${slug}/`],
            [`${slug}/`, `article/${slug}/`],
          ]),
        ];
        const lines = [
          "# Generated by src/lib/redirects.mjs at build time; don't edit by hand.",
          "# Old Gatsby article URLs (/<slug>/) -> /article/<slug>/",
          ...rules.map(([from, to]) => `${base}${from} ${base}${to} 301`),
        ];
        writeFileSync(new URL("_redirects", dir), `${lines.join("\n")}\n`);
        logger.info(`Wrote ${rules.length} redirects to _redirects`);
      },
    },
  };
}
