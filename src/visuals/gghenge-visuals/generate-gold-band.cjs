const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root = __dirname;
const html = fs.readFileSync(path.join(root, 'index_fa26.html'), 'utf8');
const solarFiles = ['solar-ephemeris.js', 'solar-calculations.js'].map(name => fs.readFileSync(path.join(root, name), 'utf8'));
const constants = ['BASE_YEAR', 'DAY_MS', 'MIN_DAY', 'MAX_DAY', 'MIDPOINT', 'NORTH_TOWER', 'SOUTH_TOWER', 'GRID_LNG_MIN', 'GRID_LNG_MAX', 'GRID_LAT_MIN', 'GRID_LAT_MAX', 'GRID_STEP_DEG']
  .map(name => html.match(new RegExp('const ' + name + ' = [^;]+;'))[0]).join('\n');
const calendar = html.slice(html.indexOf('function calendarDay('), html.indexOf('function doyToDateStr('));
const geometry = html.slice(html.indexOf('function degToRad('), html.indexOf('function updateClickedSunsetPopup('));
const source = [...solarFiles, constants, calendar, geometry].join('\n');
const signature = crypto.createHash('sha256').update(source).digest('hex');
const target = path.join(root, 'gold-band.js');
if (process.argv.includes('--check')) {
  const context = vm.createContext({});
  vm.runInContext(fs.readFileSync(target, 'utf8'), context);
  if (context.GGHBandData.signature !== signature) {
    throw new Error('Gold band data is stale. Run node generate-gold-band.cjs');
  }
  console.log('PASS: prepared gold bands match the current calculation sources.');
} else {
  const context = vm.createContext({});
  vm.runInContext(source, context);
  const days = vm.runInContext(`Object.fromEntries(Array.from({length: MAX_DAY - MIN_DAY + 1}, (_, i) => {
    const day = MIN_DAY + i;
    return [day, calculateBoundaryFillGeoJSON(day)];
  }))`, context);
  fs.writeFileSync(target, '// Generated by node generate-gold-band.cjs. Do not edit by hand.\n' +
    'globalThis.GGHBandData = ' + JSON.stringify({signature, days}) + ';\n');
  console.log(`Prepared ${Object.keys(days).length} daily gold bands (${fs.statSync(target).size} bytes).`);
}
