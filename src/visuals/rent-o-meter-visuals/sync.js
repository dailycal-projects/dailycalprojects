// Copies the rent-o-meter app (berkeley-rent-registry/dc_app, a standalone Vite app and the source of truth)
// into this article. Rerun after anything there changes:
//
//   node src/visuals/rent-o-meter-visuals/sync.js <path-to-dc_app>
//
// What it writes, none of which should be edited by hand:
//   app/              dc_app/src as is, except host.ts (written below) and the Vite-only entry and stylesheet
//   styles/app.css    dc_app/src/styles.css, every rule scoped to .rom, the root RentOMeterStory renders
//   static/rent-o-meter/   the data files, images and fonts the app fetches at run time
//
// Gatsby puts every imported stylesheet on every page of the site, and the app's CSS was written for a page
// of its own (`:root` variables, `html, body` rules, bare element selectors, short keyframe names). Scoped,
// none of it reaches another article. Same approach as ac-transit-visuals/scope-css.js.
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const source = process.argv[2];
if (!source) {
  console.error('usage: node sync.js <path-to-dc_app>');
  process.exit(1);
}
const HERE = __dirname;
const SITE = path.resolve(HERE, '../../..');
const ROOT = '.rom';
const PUBLIC_DIR = 'rent-o-meter'; // served at /rent-o-meter/; host.ts below must match

// --- source -------------------------------------------------------------------------------------------

const SKIP = new Set(['main.tsx', 'styles.css', 'host.ts']);
const app = path.join(HERE, 'app');
fs.rmSync(app, { recursive: true, force: true });
(function copy(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const name of fs.readdirSync(from)) {
    const f = path.join(from, name);
    if (fs.statSync(f).isDirectory()) copy(f, path.join(to, name));
    else if (!SKIP.has(name) && !/\.test\.tsx?$/.test(name)) fs.copyFileSync(f, path.join(to, name));
  }
}(path.join(source, 'src'), app));

fs.writeFileSync(path.join(app, 'host.ts'), `// Generated by sync.js: the data.dailycal.org version of dc_app/src/host.ts.

/** The URL prefix public/ is served from, ending in a slash: the site's static/${PUBLIC_DIR}/. */
export const assetBase: string = "/${PUBLIC_DIR}/";

/** Sheets and dialogs portal into the article's root, so the app's scoped styles reach them. */
export function portalTarget(): HTMLElement {
  return document.querySelector<HTMLElement>("${ROOT}") ?? document.body;
}
`);
console.log(`src -> ${path.relative(SITE, app)}`);

// --- styles -------------------------------------------------------------------------------------------

function scopeSelector(selector) {
  const s = selector.trim();
  if (s === ':root' || s === 'html' || s === 'body') return ROOT;
  // the app locks the page behind its story and sheets by putting this class on the real body
  if (s === 'body.locked') return s;
  if (s === '*') return `${ROOT} *`;
  return `${ROOT} ${s}`;
}

const scope = () => ({
  postcssPlugin: 'scope',
  Rule(rule) {
    if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    if (rule.selector.startsWith(ROOT)) return;
    rule.selectors = [...new Set(rule.selectors.map(scopeSelector))];
  },
  AtRule: {
    keyframes(at) {
      if (!at.params.startsWith('rom-')) at.params = `rom-${at.params}`;
    },
  },
});
scope.postcss = true;

// keyframe names are global too: prefix them, and every animation that uses one
function renameAnimations(root) {
  const names = new Set();
  root.walkAtRules(/keyframes$/, (at) => names.add(at.params.replace(/^rom-/, '')));
  root.walkDecls(/^animation(-name)?$/, (decl) => {
    decl.value = decl.value.replace(/[\w-]+/g, (w) => (names.has(w) ? `rom-${w}` : w));
  });
}

// The site's typography plugin and MUI baseline style bare h1, p, a, button and so on. The app was written
// against browser defaults, so inside the root those elements go back to them; the app's own rules outrank
// this one.
const RESET = `/* Generated by sync.js from dc_app/src/styles.css. Do not edit by hand. */
${ROOT} :where(h1, h2, h3, h4, h5, h6, p, ul, ol, li, dl, dd, dt, a, button, input, select, textarea, label,
  table, thead, tbody, tr, th, td, figure, figcaption, blockquote, small, strong, b, em, i, code, pre, hr, img,
  time, header, section) {
  all: revert;
}
`;

const css = fs.readFileSync(path.join(source, 'src/styles.css'), 'utf8');
const parsed = postcss.parse(css);
renameAnimations(parsed);
const out = postcss([scope]).process(parsed, { from: 'styles.css' }).css;
fs.mkdirSync(path.join(HERE, 'styles'), { recursive: true });
fs.writeFileSync(path.join(HERE, 'styles/app.css'), RESET + out);
console.log('styles.css -> styles/app.css');

// --- data ---------------------------------------------------------------------------------------------

const DATA = ['buildings', 'districts', 'landlords', 'owners', 'rentometer', 'streets', 'blocks'];
const pub = path.join(SITE, 'static', PUBLIC_DIR);
fs.rmSync(pub, { recursive: true, force: true });
fs.mkdirSync(path.join(pub, 'data/tiles'), { recursive: true });
for (const f of DATA) fs.copyFileSync(path.join(source, `public/data/${f}.json`), path.join(pub, `data/${f}.json`));
const tiles = path.join(source, 'public/data/tiles');
for (const f of fs.readdirSync(tiles)) fs.copyFileSync(path.join(tiles, f), path.join(pub, 'data/tiles', f));
fs.copyFileSync(path.join(source, 'public/dailycal-wordmark.webp'), path.join(pub, 'dailycal-wordmark.webp'));
fs.mkdirSync(path.join(pub, 'fonts'));
const fonts = path.join(source, 'public/fonts');
for (const f of fs.readdirSync(fonts)) fs.copyFileSync(path.join(fonts, f), path.join(pub, 'fonts', f));
console.log(`public -> static/${PUBLIC_DIR}`);
